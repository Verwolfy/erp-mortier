-- VERSION TEST UNIQUEMENT : à exécuter dans Supabase SQL Editor sur un projet séparé.
-- Modèles métier inchangés : stock_actuel, stock_actuel_pf, lots, mouvements,
-- mouvements_pf. Deux tables TECHNIQUES ajoutées : journal idempotence et outbox.
-- Ne PAS déployer avant inventaire/réconciliation des lots et validation RLS.

BEGIN;

CREATE TABLE IF NOT EXISTS public.erp_stock_operations (
    operation_id text PRIMARY KEY,
    request_payload jsonb NOT NULL,
    result_payload jsonb,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.erp_stock_outbox (
    event_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    operation_id text NOT NULL UNIQUE REFERENCES public.erp_stock_operations(operation_id),
    payload jsonb NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    synced_at timestamptz
);

CREATE OR REPLACE FUNCTION public.erp_apply_stock_movement(
    p_operation_id text,
    p_item_type text,
    p_direction text,
    p_item_id text,
    p_quantity numeric,
    p_unit_cost numeric,
    p_reference text,
    p_expiry text
) RETURNS jsonb
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = pg_catalog, public
AS $body$
DECLARE
    v_request jsonb;
    v_prior_request jsonb;
    v_prior_result jsonb;
    v_result jsonb;
    v_qty numeric;
    v_existing_qty numeric;
    v_existing_cost numeric;
    v_new_qty numeric;
    v_new_cost numeric;
    v_needed numeric;
    v_taken numeric;
    v_cost_total numeric := 0;
    v_lot record;
    v_lot_id text;
    v_movement_id text;
    v_now text := to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS');
    v_lot_updates jsonb := '[]'::jsonb;
BEGIN
    IF p_operation_id IS NULL OR length(btrim(p_operation_id)) = 0
       OR length(p_operation_id) > 128 THEN
        RAISE EXCEPTION 'Identifiant d opération obligatoire (<=128)' USING ERRCODE = '22023';
    END IF;
    IF p_item_type NOT IN ('MP', 'PF') OR p_item_type IS NULL
       OR p_direction NOT IN ('ENTREE', 'SORTIE') OR p_direction IS NULL THEN
        RAISE EXCEPTION 'Type ou direction de stock invalide' USING ERRCODE = '22023';
    END IF;
    IF p_item_id IS NULL OR length(btrim(p_item_id)) = 0 OR length(p_item_id) > 200
       OR p_reference IS NULL OR length(btrim(p_reference)) = 0 OR length(p_reference) > 500 THEN
        RAISE EXCEPTION 'Article ou référence invalide' USING ERRCODE = '22023';
    END IF;
    IF p_quantity IS NULL OR p_quantity::text IN ('NaN', 'Infinity', '-Infinity') OR p_quantity <= 0 OR p_quantity >= 1000000000000000 THEN
        RAISE EXCEPTION 'Quantité doit être positive et finie' USING ERRCODE = '22023';
    END IF;
    IF p_direction = 'ENTREE' AND (
       p_unit_cost IS NULL OR p_unit_cost::text IN ('NaN', 'Infinity', '-Infinity')
       OR p_unit_cost < 0 OR p_unit_cost >= 1000000000000000) THEN
        RAISE EXCEPTION 'Coût de réception invalide' USING ERRCODE = '22023';
    END IF;
    IF p_direction = 'SORTIE' AND p_unit_cost IS NOT NULL THEN
        RAISE EXCEPTION 'Coût interdit sur une sortie (CMP en base)' USING ERRCODE = '22023';
    END IF;
    IF p_expiry IS NOT NULL AND length(p_expiry) > 40 THEN
        RAISE EXCEPTION 'Date de péremption invalide' USING ERRCODE = '22023';
    END IF;

    -- Protection contre les doublons et les réémissions après timeout réseau.
    v_request := jsonb_build_object('type', p_item_type, 'direction', p_direction,
                                   'item_id', p_item_id, 'quantity', p_quantity,
                                   'unit_cost', p_unit_cost, 'reference', p_reference,
                                   'expiry', p_expiry);
    INSERT INTO public.erp_stock_operations(operation_id, request_payload)
    VALUES (p_operation_id, v_request)
    ON CONFLICT (operation_id) DO NOTHING;

    SELECT request_payload, result_payload
      INTO v_prior_request, v_prior_result
      FROM public.erp_stock_operations WHERE operation_id = p_operation_id FOR UPDATE;
    IF v_prior_request IS DISTINCT FROM v_request THEN
        RAISE EXCEPTION 'Identifiant d opération réutilisé avec un autre contenu'
            USING ERRCODE = '23505';
    END IF;
    IF v_prior_result IS NOT NULL THEN
        RETURN v_prior_result;
    END IF;

    -- Serrure par (MP/PF, article) pour sérialiser les appels à CETTE RPC.
    -- Toute autre écriture historique doit être arrêtée avant activation.
    PERFORM pg_advisory_xact_lock(hashtextextended('ERP_STOCK:' || p_item_type || ':' || p_item_id, 0));

    -- Vérifier que l'article existe, sans modifier les référentiels métier.
    IF p_item_type = 'MP' THEN
        PERFORM 1 FROM public.matieres_premieres WHERE mp_id = p_item_id;
    ELSE
        PERFORM 1 FROM public.sku_conditionnement WHERE sku_id = p_item_id;
    END IF;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'Article inexistant dans le référentiel' USING ERRCODE = '23503';
    END IF;

    IF p_item_type = 'MP' THEN
        SELECT quantite_disponible, cmp_actuel INTO v_existing_qty, v_existing_cost
          FROM public.stock_actuel WHERE mp_id = p_item_id FOR UPDATE;
    ELSE
        SELECT quantite_disponible, cout_revient INTO v_existing_qty, v_existing_cost
          FROM public.stock_actuel_pf WHERE sku_id = p_item_id FOR UPDATE;
    END IF;

    IF p_direction = 'ENTREE' THEN
        v_qty := coalesce(v_existing_qty, 0);
        IF v_qty < 0 OR v_qty::text IN ('NaN', 'Infinity', '-Infinity')
           OR coalesce(v_existing_cost, 0) < 0
           OR coalesce(v_existing_cost, 0)::text IN ('NaN', 'Infinity', '-Infinity') THEN
            RAISE EXCEPTION 'Stock ou coût existant invalide' USING ERRCODE = '23514';
        END IF;
        v_new_qty := v_qty + p_quantity;
        v_new_cost := ((v_qty * coalesce(v_existing_cost, 0)) +
                       (p_quantity * p_unit_cost)) / v_new_qty;

        IF p_item_type = 'MP' THEN
            INSERT INTO public.stock_actuel(mp_id, quantite_disponible, cmp_actuel, derniere_maj)
            VALUES (p_item_id, v_new_qty, v_new_cost, v_now)
            ON CONFLICT (mp_id) DO UPDATE SET
                quantite_disponible = EXCLUDED.quantite_disponible,
                cmp_actuel = EXCLUDED.cmp_actuel,
                derniere_maj = EXCLUDED.derniere_maj;
        ELSE
            INSERT INTO public.stock_actuel_pf(sku_id, quantite_disponible, cout_revient, derniere_maj)
            VALUES (p_item_id, v_new_qty, v_new_cost, v_now)
            ON CONFLICT (sku_id) DO UPDATE SET
                quantite_disponible = EXCLUDED.quantite_disponible,
                cout_revient = EXCLUDED.cout_revient,
                derniere_maj = EXCLUDED.derniere_maj;
        END IF;

        v_lot_id := 'LOT-' || gen_random_uuid()::text;
        INSERT INTO public.lots(lot_id, item_id, type_item, date_creation, date_peremption,
                                quantite_initiale, quantite_restante, statut)
        VALUES (v_lot_id, p_item_id, p_item_type, v_now, p_expiry,
                p_quantity, p_quantity, 'ACTIF');

        IF p_item_type = 'MP' THEN
            v_movement_id := 'MOUV-' || gen_random_uuid()::text;
            INSERT INTO public.mouvements(mouvement_id, date, type_mouvement, mp_id,
                                         quantite, reference, lot_id, prix_entree)
            VALUES (v_movement_id, v_now, 'ENTREE', p_item_id,
                    p_quantity, p_reference, v_lot_id, p_unit_cost);
        ELSE
            v_movement_id := 'MOUVPF-' || gen_random_uuid()::text;
            INSERT INTO public.mouvements_pf(mouvement_pf_id, date, type_mouvement,
                                            sku_id, quantite, reference, lot_id, cout_unitaire)
            VALUES (v_movement_id, v_now, 'ENTREE', p_item_id,
                    p_quantity, p_reference, v_lot_id, p_unit_cost);
        END IF;
        v_result := jsonb_build_object('operation_id', p_operation_id,
                         'quantity_remaining', v_new_qty, 'cost_total', 0,
                         'lot_id', v_lot_id, 'movement_count', 1);
    ELSE
        IF v_existing_qty IS NULL OR v_existing_qty::text IN ('NaN', 'Infinity', '-Infinity')
           OR v_existing_qty < p_quantity THEN
            RAISE EXCEPTION 'Stock global insuffisant' USING ERRCODE = '23514';
        END IF;
        IF v_existing_cost IS NULL OR v_existing_cost < 0
           OR v_existing_cost::text IN ('NaN', 'Infinity', '-Infinity') THEN
            RAISE EXCEPTION 'CMP/coût de revient non défini' USING ERRCODE = '23514';
        END IF;
        v_needed := p_quantity;
        -- FIFO : tri déterministe. Chaque lot est verrouillé dans la transaction.
        FOR v_lot IN
            SELECT lot_id, quantite_restante FROM public.lots
             WHERE type_item = p_item_type AND item_id = p_item_id
               AND statut = 'ACTIF' AND quantite_restante > 0
             ORDER BY date_creation ASC NULLS LAST, lot_id ASC
             FOR UPDATE
        LOOP
            EXIT WHEN v_needed = 0;
            v_taken := least(v_lot.quantite_restante, v_needed);
            UPDATE public.lots
               SET quantite_restante = v_lot.quantite_restante - v_taken,
                   statut = CASE WHEN v_lot.quantite_restante = v_taken THEN 'EPUISE' ELSE 'ACTIF' END
             WHERE lot_id = v_lot.lot_id;
            IF p_item_type = 'MP' THEN
                v_movement_id := 'MOUV-' || gen_random_uuid()::text;
                INSERT INTO public.mouvements(mouvement_id, date, type_mouvement, mp_id,
                                             quantite, reference, lot_id, prix_entree)
                VALUES (v_movement_id, v_now, 'SORTIE', p_item_id, v_taken,
                        p_reference, v_lot.lot_id, v_existing_cost);
            ELSE
                v_movement_id := 'MOUVPF-' || gen_random_uuid()::text;
                INSERT INTO public.mouvements_pf(mouvement_pf_id, date, type_mouvement,
                                                sku_id, quantite, reference, lot_id, cout_unitaire)
                VALUES (v_movement_id, v_now, 'SORTIE', p_item_id, v_taken,
                        p_reference, v_lot.lot_id, v_existing_cost);
            END IF;
            v_lot_updates := v_lot_updates || jsonb_build_array(jsonb_build_object(
                            'lot_id', v_lot.lot_id, 'taken', v_taken));
            v_needed := v_needed - v_taken;
        END LOOP;
        IF v_needed <> 0 THEN
            RAISE EXCEPTION 'Incohérence globale / somme des lots : opération annulée'
                USING ERRCODE = '23514';
        END IF;
        v_new_qty := v_existing_qty - p_quantity;
        IF p_item_type = 'MP' THEN
            UPDATE public.stock_actuel SET quantite_disponible = v_new_qty,
                derniere_maj = v_now WHERE mp_id = p_item_id;
        ELSE
            UPDATE public.stock_actuel_pf SET quantite_disponible = v_new_qty,
                derniere_maj = v_now WHERE sku_id = p_item_id;
        END IF;
        v_cost_total := p_quantity * v_existing_cost;
        v_result := jsonb_build_object('operation_id', p_operation_id,
                         'quantity_remaining', v_new_qty, 'cost_total', v_cost_total,
                         'lot_allocations', v_lot_updates,
                         'movement_count', jsonb_array_length(v_lot_updates));
    END IF;

    UPDATE public.erp_stock_operations SET result_payload = v_result
     WHERE operation_id = p_operation_id;
    INSERT INTO public.erp_stock_outbox(operation_id, payload)
    VALUES (p_operation_id, jsonb_build_object(
        'operation_id', p_operation_id, 'item_type', p_item_type,
        'direction', p_direction, 'item_id', p_item_id,
        'reference', p_reference, 'result', v_result));
    RETURN v_result;
END;
$body$;

-- API privée : seule la clé service_role serveur peut exécuter cette fonction.
REVOKE ALL ON FUNCTION public.erp_apply_stock_movement(text,text,text,text,numeric,numeric,text,text)
    FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.erp_apply_stock_movement(text,text,text,text,numeric,numeric,text,text)
    TO service_role;

REVOKE ALL ON public.erp_stock_operations, public.erp_stock_outbox FROM PUBLIC, anon, authenticated;
GRANT SELECT, INSERT, UPDATE ON public.erp_stock_operations, public.erp_stock_outbox TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.erp_stock_outbox_event_id_seq TO service_role;

COMMIT;
